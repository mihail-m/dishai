"""Trace Brain-Lung-Icon.png into the DishAI logo: a vector path for the app and the favicon, and PNG icons for installs.

    .venv/bin/python scripts/make_logo.py [source.png]

Writes public/icon.svg, public/icon-192.png, icon-512.png, icon-maskable-512.png, public/apple-touch-icon.png and
frontend/src/components/logoPath.ts (the path the <Logo> component draws, so it follows the light and dark theme colours).
The artwork is white lines on green; only the white shape is kept and re-coloured with the app's own accent green.
"""
import sys
from pathlib import Path

import contourpy
import numpy as np
from PIL import Image, ImageDraw
from scipy.ndimage import gaussian_filter

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "Brain-Lung-Icon.png"
GREEN, GREEN_TOP = "#1f5b3f", "#2f7a55"  # the app's --accent, and the lighter top of the tile
FIT = 22.5  # the artwork spans this many of the 32 units of the tile


def rdp(pts: np.ndarray, eps: float) -> np.ndarray:
    """Douglas-Peucker on an open polyline."""
    if len(pts) < 3:
        return pts
    a, b = pts[0], pts[-1]
    ab = b - a
    n = np.hypot(*ab) or 1e-9
    d = np.abs(ab[0] * (pts[:, 1] - a[1]) - ab[1] * (pts[:, 0] - a[0])) / n
    k = int(d.argmax())
    if d[k] <= eps:
        return np.array([a, b])
    return np.vstack([rdp(pts[: k + 1], eps)[:-1], rdp(pts[k:], eps)])


def smooth_path(pts: np.ndarray, f) -> str:
    """Closed Catmull-Rom spline through the points, as cubic Bezier segments."""
    n = len(pts)
    out = [f"M{f(pts[0])}"]
    for i in range(n):
        p0, p1, p2, p3 = pts[(i - 1) % n], pts[i], pts[(i + 1) % n], pts[(i + 2) % n]
        c1, c2 = p1 + (p2 - p0) / 6.0, p2 - (p3 - p1) / 6.0
        out.append(f"C{f(c1)} {f(c2)} {f(p2)}")
    return "".join(out) + "Z"


def main() -> None:
    im = np.asarray(Image.open(SRC).convert("RGB"), dtype=float)
    mask = gaussian_filter(im[:, :, 0] / 255.0, 1.1)  # white = 1, green = ~0.02 in the red channel
    h, w = mask.shape
    gen = contourpy.contour_generator(np.arange(w, dtype=float), np.arange(h, dtype=float), mask)
    loops = [np.asarray(l) for l in gen.lines(0.5)]
    loops = [l[:-1] for l in loops if len(l) > 8 and abs(0.5 * np.sum(l[:-1, 0] * np.roll(l[:-1, 1], -1) - np.roll(l[:-1, 0], -1) * l[:-1, 1])) > 40]
    allp = np.vstack(loops)
    (x0, y0), (x1, y1) = allp.min(0), allp.max(0)
    s = FIT / max(x1 - x0, y1 - y0)
    ox, oy = 16 - s * (x0 + x1) / 2, 16 - s * (y0 + y1) / 2 + 0.2
    f = lambda p: f"{p[0] * s + ox:.2f},{p[1] * s + oy:.2f}".replace(".00", "")
    def simplify_closed(l: np.ndarray) -> np.ndarray:
        k = int(np.hypot(*(l - l[0]).T).argmax())  # split at the point farthest from the start: Douglas-Peucker needs two different ends
        return np.vstack([rdp(l[: k + 1], 0.9)[:-1], rdp(np.vstack([l[k:], l[:1]]), 0.9)[:-1]])

    d = "".join(smooth_path(simplify_closed(l), f) for l in loops)

    ART = f'<path fill="#fff" fill-rule="evenodd" d="{d}"/>'
    defs = ('<defs><linearGradient id="g" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#fff" stop-opacity=".16"/>'
            '<stop offset="1" stop-color="#fff" stop-opacity="0"/></linearGradient></defs>')
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">{defs}<rect width="32" height="32" rx="9" fill="{GREEN}"/>'
           f'<rect width="32" height="32" rx="9" fill="url(#g)"/>{ART}</svg>')
    (ROOT / "public" / "icon.svg").write_text(svg + "\n")
    (ROOT / "frontend/src/components/logoPath.ts").write_text(
        "// Generated by scripts/make_logo.py from Brain-Lung-Icon.png: the brain-and-lungs mark, in a 32 x 32 box. Do not edit by hand.\n"
        f'export const LOGO_PATH = "{d}";\n')

    # PNG icons: the same artwork, scaled from the traced mask so the edges stay clean at any size
    crop = Image.fromarray((np.clip(mask, 0, 1) * 255).astype("uint8")).crop((int(x0) - 2, int(y0) - 2, int(x1) + 3, int(y1) + 3))

    def icon(size: int, art: float, rounded: bool) -> Image.Image:
        big = size * 4
        tile = Image.new("RGB", (big, big), GREEN)
        top = Image.new("RGB", (big, big), "#ffffff")
        grad = Image.linear_gradient("L").resize((big, big)).point(lambda v: int(255 - v) * 41 // 255)  # white overlay, strongest at the top
        tile.paste(top, (0, 0), grad)
        side = int(big * art)
        sc = side / max(crop.size)
        m = crop.resize((round(crop.width * sc), round(crop.height * sc)), Image.LANCZOS)
        tile.paste(Image.new("RGB", m.size, "#ffffff"), ((big - m.width) // 2, (big - m.height) // 2 + int(big * 0.006)), m)
        tile = tile.convert("RGBA")
        if rounded:
            cut = Image.new("L", (big, big), 0)
            ImageDraw.Draw(cut).rounded_rectangle((0, 0, big - 1, big - 1), radius=int(big * 9 / 32), fill=255)
            tile.putalpha(cut)
        return tile.resize((size, size), Image.LANCZOS)

    pub = ROOT / "public"
    icon(192, FIT / 32, True).save(pub / "icon-192.png")
    icon(512, FIT / 32, True).save(pub / "icon-512.png")
    icon(512, 0.56, False).save(pub / "icon-maskable-512.png")  # full bleed, artwork inside the safe zone
    icon(180, 0.66, False).save(pub / "apple-touch-icon.png")
    print(f"path {len(d) / 1024:.1f} KB, {len(loops)} outlines")


if __name__ == "__main__":
    main()
